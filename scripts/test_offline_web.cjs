// Çevrimdışı PWA, Service Worker önbelleği, çevrimdışı 030 ipucu/açıklama ve
// yeniden bağlantı davranışını gerçek tarayıcıda doğrular.
// node scripts/test_offline_web.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const engines = require('playwright');

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.xml': 'application/xml; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
};

(async () => {
  const root = path.resolve(__dirname, '../docs');
  assert.ok(fs.existsSync(path.join(root, 'sw.js')), 'docs/sw.js must be generated by build_web.py');
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'site.webmanifest'), 'utf8'));
  assert.equal(manifest.id, './', 'manifest must declare a stable id');
  assert.equal(manifest.start_url, './');
  assert.equal(manifest.display, 'standalone');

  const server = http.createServer((req, res) => {
    const pathname = new URL(req.url, 'http://localhost').pathname;
    const rel = pathname === '/' ? '/index.html' : pathname;
    const file = path.resolve(root, '.' + rel);
    if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
      res.writeHead(404);
      return res.end();
    }
    const ext = path.extname(file);
    res.writeHead(200, { 'Content-Type': MIME[ext] || 'application/octet-stream' });
    res.end(fs.readFileSync(file));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}/`;
  const engine = process.env.WEB_TEST_BROWSER || 'chromium';
  let browser;
  try {
    browser = await engines[engine].launch({
      headless: true,
      ...(engine === 'chromium' && process.env.MOBILE_BROWSER_EXECUTABLE
        ? { executablePath: process.env.MOBILE_BROWSER_EXECUTABLE } : {}),
    });
    const context = await browser.newContext({
      viewport: { width: 390, height: 844 },
      isMobile: true,
      hasTouch: true,
      serviceWorkers: 'allow',
      reducedMotion: 'reduce',
    });
    // Dış ağ isteklerini kes (uçak modu / izole test)
    await context.route('**/*', route =>
      route.request().url().startsWith(base) ? route.continue() : route.abort());
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));

    const a11y = async name => {
      if (!await page.evaluate(() => !!window.axe)) {
        await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') });
      }
      const violations = await page.evaluate(async () => (await axe.run(document, {
        runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa', 'best-practice'] },
      })).violations.map(v => ({ id: v.id, impact: v.impact, nodes: v.nodes.map(n => n.target) })));
      assert.deepEqual(violations, [], `${engine}: offline a11y ${name}`);
    };

    await page.goto(base, { waitUntil: 'load' });

    // Chromium'da Service Worker tam olarak kurulup önbelleği doldurmalı.
    // (Playwright WebKit yerel HTTP üzerinde SW kayıtlarını kısıtlayabilir; varsa onu da sınarız.)
    const swReady = await page.evaluate(async () => {
      if (!('serviceWorker' in navigator)) return false;
      try {
        const reg = await Promise.race([
          navigator.serviceWorker.ready,
          new Promise(r => setTimeout(() => r(null), 5000)),
        ]);
        if (!reg || !reg.active) return false;
        const hit = await caches.match('./index.html', { ignoreSearch: true });
        return !!hit;
      } catch (e) {
        return false;
      }
    });
    if (engine === 'chromium') {
      assert.equal(swReady, true, 'Service Worker must precache ./index.html on Chromium');
    }

    // 030 (Flight Performance and Planning) dersini seç ve doğruda otomatik geçişi kapat
    await page.locator('#mPick').tap();
    await page.locator('#tree [data-solo="030"]:not([data-c])').tap();
    await page.locator('#optBox > summary').tap();
    await page.locator('#swAutoNext').tap();
    await page.locator('#settingsBack').tap();

    // Durum panelinde çevrimdışı hazırlık bilgisini kontrol et
    await page.locator('#bStats').tap();
    await page.locator('#statsAccount > summary').tap();
    assert.ok(await page.locator('#offlineBox').isVisible());
    if (swReady) {
      await page.waitForFunction(() =>
        (document.querySelector('#offlineBox')?.textContent || '').includes('Çevrimdışı çalışmaya hazır'));
    }
    await page.locator('#sheetClose').tap();

    // GERÇEK ÇEVRİMDIŞI MODA GEÇ (uçak modu!)
    await context.setOffline(true);
    await page.evaluate(() => window.dispatchEvent(new Event('offline')));
    await page.waitForFunction(() => !document.querySelector('#offPill').classList.contains('hidden'));
    await a11y('offline home');

    // Dar telefonda (320px) çevrimdışı rozeti taşmamalı
    await page.setViewportSize({ width: 320, height: 568 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= 320), '320px offline home overflow');
    await page.setViewportSize({ width: 390, height: 844 });

    // Service Worker aktifse tamamen çevrimdışıyken soğuk yeniden yükleme (reload) çalışmalı!
    if (swReady) {
      await page.reload({ waitUntil: 'load' });
      await page.waitForFunction(() => !!document.querySelector('#go'));
      await page.waitForFunction(() => !document.querySelector('#offPill').classList.contains('hidden'));
    }

    // Çevrimdışıyken 030 turuna başla
    await page.locator('#go').tap();
    await page.waitForSelector('.opt');

    // Çevrimdışıyken #ask düğmesi dış bağlantı değil, çevrimdışı İpucu düğmesi olmalı
    const askInfo = await page.evaluate(() => {
      const el = document.querySelector('#ask');
      return { tag: el.tagName, text: el.textContent.trim(), off: el.dataset.off };
    });
    assert.equal(askInfo.tag, 'BUTTON');
    assert.equal(askInfo.off, 'exp');
    assert.equal(askInfo.text, 'İpucu');

    // İpucu düğmesine bas -> cevabı ele vermeyen ipucu kutusu açılmalı
    await page.locator('#ask').tap();
    assert.ok(await page.locator('#xHelp').isVisible());
    assert.ok((await page.locator('#xHelp .xbody').textContent()).trim().length > 20);
    await a11y('offline hint');

    // Tam açıklamayı gör -> #xNote + TR/EN geçişi çalışmalı
    await page.locator('#xShowFull').tap();
    assert.ok(await page.locator('#xNote').isVisible());
    const trExp = (await page.locator('#xNote .xbody').textContent()).trim();
    assert.ok(trExp.length > 40);
    await page.locator('#xNote [data-elang="en"]').tap();
    const enExp = (await page.locator('#xNote .xbody').textContent()).trim();
    assert.ok(enExp.length > 40 && enExp !== trExp, 'EN explanation must differ from TR');
    await page.locator('#xNote [data-elang="tr"]').tap();
    await a11y('offline explanation');

    // Bir soruyu doğru cevapla (autoNext kapalı -> açıklama ekranda kalmalı, otomatik atlamamalı!)
    const rightIdx = await page.evaluate(() => {
      const db = JSON.parse(document.querySelector('#qdata').textContent);
      const id = +document.querySelector('.card .head > .lbl.num').textContent;
      const q = db.q.find(x => x[0] === id);
      const correct = (q[13] || q[4])[0];
      return [...document.querySelectorAll('.opt')].findIndex(b => b.children[1].textContent === correct);
    });
    assert.ok(rightIdx >= 0);
    await page.locator('.opt').nth(rightIdx).tap();
    await page.waitForTimeout(750);
    assert.ok(await page.locator('.verdict.ok').isVisible(), 'Must stay on question when autoNext is off');
    assert.ok(await page.locator('#xNote').isVisible(), 'Explanation must be visible after answering');
    assert.match(await page.locator('#navBtn').textContent(), /^1\//);

    // Sonraki soruya geç ve yanlış cevapla -> açıklama otomatik gelmeli
    await page.locator('#next').tap();
    assert.match(await page.locator('#navBtn').textContent(), /^2\//);
    const wrongIdx = await page.evaluate(() => {
      const db = JSON.parse(document.querySelector('#qdata').textContent);
      const id = +document.querySelector('.card .head > .lbl.num').textContent;
      const q = db.q.find(x => x[0] === id);
      const correct = (q[13] || q[4])[0];
      return [...document.querySelectorAll('.opt')].findIndex(b => b.children[1].textContent !== correct);
    });
    await page.locator('.opt').nth(wrongIdx).tap();
    assert.ok(await page.locator('.verdict.bad').isVisible());
    assert.ok(await page.locator('#xNote').isVisible());
    assert.ok((await page.locator('#xNote .xbody').textContent()).trim().length > 40);

    // Çevrimdışı ders notları gömülü olarak açılmalı
    await page.locator('#quizMore').tap();
    await page.locator('#quizNotes').tap();
    assert.ok(await page.locator('.noteitem').count() > 0);
    await page.locator('#sheetClose').tap();

    // Uçuş ortasında tarayıcı kapanıp açılsa (offline reload) tur ve cevaplar korunmalı!
    if (swReady) {
      await page.reload({ waitUntil: 'load' });
      await page.waitForSelector('#navBtn');
      assert.match(await page.locator('#navBtn').textContent(), /^2\//);
      assert.ok(await page.locator('.verdict.bad').isVisible(), 'Answered state must survive offline reload');
      assert.ok(await page.locator('#xNote').isVisible(), 'Explanation must survive offline reload');
    }

    // Turu bitir -> raporda yanlış sorunun açıklaması açık görünmeli
    await page.locator('#quizMore').tap();
    await page.locator('#quit').tap();
    assert.ok(await page.locator('.rrow .rexp[open]').count() >= 1, 'Wrong question explanation must be open in report');

    // İnternet geri gelince çevrimdışı rozeti gizlenmeli
    await context.setOffline(false);
    await page.evaluate(() => window.dispatchEvent(new Event('online')));
    await page.waitForFunction(() => document.querySelector('#offPill').classList.contains('hidden'));

    assert.deepEqual(errors, [], `Unexpected page errors: ${errors.join('; ')}`);
    console.log(`${engine}: offline PWA (swReady=${swReady}), cold offline reload, 030 hints/explanations, TR/EN toggle, report and online recovery passed.`);
  } finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
